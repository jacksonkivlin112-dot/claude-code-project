import { ESPN_BASE, parseScoreboard } from './espn.js';

// Data layer: Sleeper (live stats + projections, CORS-enabled) and ESPN
// (scores, standings, schedule; via snapshot + best-effort live scores).
// Everything keys off Sleeper's NFL state, so the app rolls forward to each
// new week automatically.

const SLEEPER = 'https://api.sleeper.com';
const SLEEPER_V1 = 'https://api.sleeper.app/v1';

export const POSITIONS = ['QB', 'RB', 'WR', 'TE', 'K', 'DEF'];

export { normTeam } from './espn.js';

// Only the stat keys the UI uses are kept, which keeps the cache small.
const KEEP = [
  'pts_ppr', 'pts_half_ppr', 'pts_std', 'gp',
  'pass_att', 'pass_cmp', 'pass_yd', 'pass_td', 'pass_int',
  'rush_att', 'rush_yd', 'rush_td',
  'rec_tgt', 'rec', 'rec_yd', 'rec_td', 'fum_lost',
  'off_snp', 'tm_off_snp',
  'fgm', 'fga', 'xpm', 'fgm_lng',
  'sack', 'int', 'fum_rec', 'def_td', 'pts_allow', 'yds_allow',
];

const mem = new Map();
const LS_PREFIX = 'ge:v1:';

export function readCache(key, ttl) {
  const hit = mem.get(key);
  if (hit && Date.now() - hit.t < ttl) return hit.v;
  try {
    const raw = localStorage.getItem(LS_PREFIX + key);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Date.now() - parsed.t < ttl) {
        mem.set(key, parsed);
        return parsed.v;
      }
    }
  } catch { /* storage unavailable */ }
  return undefined;
}

export function writeCache(key, v, persist) {
  const entry = { t: Date.now(), v };
  mem.set(key, entry);
  if (!persist) return;
  try {
    localStorage.setItem(LS_PREFIX + key, JSON.stringify(entry));
  } catch {
    // Quota exceeded: drop our older entries and try once more.
    try {
      Object.keys(localStorage).filter((k) => k.startsWith(LS_PREFIX)).forEach((k) => localStorage.removeItem(k));
      localStorage.setItem(LS_PREFIX + key, JSON.stringify(entry));
    } catch { /* give up quietly */ }
  }
}

export function cacheAge(key) {
  const hit = mem.get(key);
  return hit ? hit.t : null;
}

export async function getJSON(url, { retries = 2 } = {}) {
  let lastErr;
  for (let i = 0; i <= retries; i++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return await res.json();
    } catch (e) {
      lastErr = e;
      await new Promise((r) => setTimeout(r, 400 * 2 ** i));
    }
  }
  throw lastErr;
}

export async function cached(key, ttl, loader, persist = true) {
  const hit = readCache(key, ttl);
  if (hit !== undefined) return hit;
  const v = await loader();
  writeCache(key, v, persist);
  return v;
}

export const MIN = 60 * 1000;
export const HOUR = 60 * MIN;

function pick(stats = {}) {
  const out = {};
  for (const k of KEEP) if (stats[k] != null) out[k] = stats[k];
  return out;
}

function normRow(r) {
  const p = r.player || {};
  const pos = p.position;
  if (!POSITIONS.includes(pos)) return null;
  const team = r.team || p.team;
  if (!team) return null;
  return {
    id: r.player_id,
    first: p.first_name || '',
    last: p.last_name || '',
    name: `${p.first_name || ''} ${p.last_name || ''}`.trim(),
    pos,
    team,
    opp: r.opponent || null,
    injury: p.injury_status || null,
    injuryPart: p.injury_body_part || null,
    exp: p.years_exp,
    gameDate: r.date,
    s: pick(r.stats),
  };
}

const posQuery = POSITIONS.map((p) => `position[]=${p}`).join('&');

export function getState() {
  return cached('state', 15 * MIN, () => getJSON(`${SLEEPER_V1}/state/nfl`), true);
}

/** Weekly player stats. Finished weeks are cached for days; the live week for minutes. */
export function getWeekStats(season, week, { live = false } = {}) {
  return cached(
    `stats:${season}:${week}`,
    live ? 5 * MIN : 72 * HOUR,
    async () => {
      const rows = await getJSON(`${SLEEPER}/stats/nfl/${season}/${week}?season_type=regular&${posQuery}`);
      return rows.map(normRow).filter((r) => r && (r.s.gp || r.s.pts_ppr));
    },
    true,
  );
}

export function getProjections(season, week) {
  return cached(
    `proj:${season}:${week}`,
    30 * MIN,
    async () => {
      const rows = await getJSON(
        `${SLEEPER}/projections/nfl/${season}/${week}?season_type=regular&${posQuery}&order_by=pts_ppr`,
      );
      return rows.map(normRow).filter((r) => r && r.opp && (r.s.pts_ppr || 0) >= 0.5);
    },
    true,
  );
}

// ---- ESPN ------------------------------------------------------------------
// Teams, standings and the season schedule come from a snapshot generated by
// scripts/fetch-espn.mjs (refreshed on a schedule by GitHub Actions). Live
// scores are fetched directly when the browser allows it, with the snapshot as
// fallback. In dev, Vite proxies /espn-api to ESPN so live data always works.

const ESPN_LIVE = import.meta.env.DEV ? '/espn-api' : ESPN_BASE;
let liveBlocked = false;

export function getSnapshot() {
  return cached(
    'espn-snapshot',
    10 * MIN,
    async () => {
      const res = await fetch(`${import.meta.env.BASE_URL}data/espn.json`, { cache: 'no-cache' });
      if (!res.ok) throw new Error(`Snapshot HTTP ${res.status}`);
      return res.json();
    },
    false,
  );
}

export async function fetchWithTimeout(url, ms) {
  const ctl = new AbortController();
  const id = setTimeout(() => ctl.abort(), ms);
  try {
    const res = await fetch(url, { signal: ctl.signal });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return await res.json();
  } finally {
    clearTimeout(id);
  }
}

/** Should we bother asking ESPN for live scores? Only around kickoff windows. */
function needsLive(games, generatedAt) {
  const now = Date.now();
  const stale = now - new Date(generatedAt).getTime() > 6 * HOUR;
  return games.some((g) => {
    const k = new Date(g.date).getTime();
    return g.state !== 'post' && now > k - 15 * MIN && (stale || now < k + 5 * HOUR);
  });
}

/** Week scoreboard: { games, byes, source: 'live' | 'snapshot' }. */
export async function getScoreboard(season, week, { force = false } = {}) {
  const snap = await getSnapshot();
  const fromSnap = {
    games: snap.games.filter((g) => g.week === week),
    byes: snap.byes?.[week] || [],
    source: 'snapshot',
    asOf: snap.generatedAt,
  };
  if (liveBlocked || (!force && !import.meta.env.DEV && !needsLive(fromSnap.games, snap.generatedAt))) return fromSnap;
  const key = `sb-live:${season}:${week}`;
  const hit = readCache(key, 40 * 1000);
  if (hit) return hit;
  try {
    const raw = await fetchWithTimeout(`${ESPN_LIVE}/site/v2/sports/football/nfl/scoreboard?week=${week}&seasontype=2&dates=${season}`, 6000);
    const parsed = parseScoreboard(raw);
    const live = { games: parsed.games, byes: parsed.byes.length ? parsed.byes : fromSnap.byes, source: 'live', asOf: new Date().toISOString() };
    writeCache(key, live, false);
    return live;
  } catch {
    if (!import.meta.env.DEV) liveBlocked = true; // CORS-blocked: don't keep retrying
    return fromSnap;
  }
}

export async function getTeams() {
  return (await getSnapshot()).teams;
}

export async function getStandings() {
  return (await getSnapshot()).standings;
}

export async function getTeamSchedule(abbr) {
  const snap = await getSnapshot();
  return snap.games
    .filter((g) => g.home.abbr === abbr || g.away.abbr === abbr)
    .sort((a, b) => a.week - b.week)
    .map((g) => {
      const home = g.home.abbr === abbr;
      const me = home ? g.home : g.away;
      const them = home ? g.away : g.home;
      return { week: g.week, date: g.date, home, opp: them.abbr, state: g.state, detail: g.detail, us: me.score, them: them.score, win: me.winner };
    });
}

export const headshot = (p) =>
  p.sport === 'nba'
    ? `https://sleepercdn.com/content/nba/players/thumb/${p.id}.jpg`
    : p.pos === 'DEF'
    ? `https://sleepercdn.com/images/team_logos/nfl/${p.id.toLowerCase()}.png`
    : `https://sleepercdn.com/content/nfl/players/thumb/${p.id}.jpg`;

/**
 * Live game feed (drives, plays, win probability, box score) for Game Center.
 * Fetched straight from ESPN; real browsers are allowed cross-origin access.
 */
export async function getGameSummary(eventId) {
  return fetchWithTimeout(`${ESPN_LIVE}/site/v2/sports/football/nfl/summary?event=${encodeURIComponent(eventId)}&_=${Math.floor(Date.now() / 10000)}`, 9000);
}
